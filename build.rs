extern crate cc;

use std::env;
use std::path::PathBuf;

/// The bindings committed for builds without bindgen.
const PREGENERATED: &str = "src/redisraw/bindings.rs";

#[cfg(any(feature = "bindgen-runtime", feature = "bindgen-static"))]
use bindgen::callbacks::{IntKind, ParseCallbacks};

#[cfg(any(feature = "bindgen-runtime", feature = "bindgen-static"))]
#[derive(Debug)]
struct RedisModuleCallback;

#[cfg(any(feature = "bindgen-runtime", feature = "bindgen-static"))]
impl ParseCallbacks for RedisModuleCallback {
    fn int_macro(&self, name: &str, _value: i64) -> Option<IntKind> {
        if name.starts_with("REDISMODULE_SUBEVENT_") || name.starts_with("REDISMODULE_EVENT_") {
            Some(IntKind::U64)
        } else if name.starts_with("REDISMODULE_REPLY_")
            || name.starts_with("REDISMODULE_KEYTYPE_")
            || name.starts_with("REDISMODULE_AUX_")
            || name == "REDISMODULE_OK"
            || name == "REDISMODULE_ERR"
            || name == "REDISMODULE_LIST_HEAD"
            || name == "REDISMODULE_LIST_TAIL"
        {
            // These values are used as `enum` discriminants, and thus must be `isize`.
            Some(IntKind::Custom {
                name: "isize",
                is_signed: true,
            })
        } else if name.starts_with("REDISMODULE_NOTIFY_")
            || name.starts_with("REDISMODULE_SWAP_PREFETCH_FLAG_")
        {
            // These are passed as `int` arguments to API functions.
            Some(IntKind::Int)
        } else {
            None
        }
    }
}

fn main() {
    println!("cargo:rerun-if-changed=src/redismodule.c");
    println!("cargo:rerun-if-changed=src/include/redismodule.h");
    println!("cargo:rerun-if-changed=build.rs");

    // Build a Redis pseudo-library so that we have symbols that we can link
    // against while building Rust code.
    //
    // include/redismodule.h is vendored in from the Redis project and
    // src/redismodule.c is a stub that includes it and plays a few other
    // tricks that we need to complete the build.

    const EXPERIMENTAL_API: &str = "REDISMODULE_EXPERIMENTAL_API";

    let mut build = cc::Build::new();

    build
        .define(EXPERIMENTAL_API, None)
        .file("src/redismodule.c")
        .include("src/include/")
        .compile("redismodule");

    let out_path = PathBuf::from(env::var("OUT_DIR").unwrap()).join("bindings.rs");
    println!("cargo:rerun-if-changed={PREGENERATED}");
    println!("cargo:rerun-if-env-changed=REDISMODULE_RS_CHECK_BINDINGS");

    #[cfg(any(feature = "bindgen-runtime", feature = "bindgen-static"))]
    generate_bindings(&out_path, EXPERIMENTAL_API);

    #[cfg(not(any(feature = "bindgen-runtime", feature = "bindgen-static")))]
    {
        let pointer_width = env::var("CARGO_CFG_TARGET_POINTER_WIDTH").unwrap_or_default();
        assert!(
            pointer_width == "64",
            "the pregenerated bindings are for 64-bit targets; enable the \
             bindgen-runtime or bindgen-static feature to build for {pointer_width}-bit"
        );
        // Read and write rather than copy, which would keep the source's
        // permissions: a read-only source would make the next build fail.
        let bindings =
            std::fs::read(PREGENERATED).expect("failed to read the pregenerated bindings");
        std::fs::write(&out_path, bindings).expect("failed to write the bindings");
    }
}

/// Generates the bindings into `out_path`. With `REDISMODULE_RS_CHECK_BINDINGS=1`,
/// fails if they differ from the committed ones.
#[cfg(any(feature = "bindgen-runtime", feature = "bindgen-static"))]
fn generate_bindings(out_path: &std::path::Path, experimental_api: &str) {
    let bindings = bindgen::Builder::default()
        .raw_line(
            "// Generated by build.rs with bindgen from src/include/redismodule.h. To\n\
             // regenerate, build with the bindgen-runtime feature and copy\n\
             // OUT_DIR/bindings.rs here; CI checks that this file is current.",
        )
        .clang_arg(format!("-D{experimental_api}"))
        .header("src/include/redismodule.h")
        .allowlist_var("(REDIS|Redis).*")
        .blocklist_type("__darwin_.*")
        .allowlist_type("RedisModule.*")
        .parse_callbacks(Box::new(RedisModuleCallback))
        .size_t_is_usize(true)
        .generate()
        .expect("error generating bindings");

    bindings
        .write_to_file(out_path)
        .expect("failed to write bindings to file");

    if env::var("REDISMODULE_RS_CHECK_BINDINGS").as_deref() == Ok("1") {
        // The first line names the bindgen version, which can change in a
        // patch release without changing the bindings.
        let without_version = |text: String| -> String {
            text.lines()
                .filter(|line| !line.starts_with("/* automatically generated by rust-bindgen"))
                .collect::<Vec<_>>()
                .join("\n")
        };
        let generated = without_version(
            std::fs::read_to_string(out_path).expect("failed to read the bindings"),
        );
        let committed = without_version(std::fs::read_to_string(PREGENERATED).unwrap_or_default());
        assert!(
            generated == committed,
            "{PREGENERATED} differs from the bindings bindgen generates; copy {} over it",
            out_path.display()
        );
    }
}
